package io.github.gcbond.openhc.core.nearby

/**
 * 控制通道承载在什么上。三种承载上的帧格式、帧加密和通道管理条目都相同，区别只有下表几处：
 *
 * | 承载 | 通道号 | 车机在握手里的角色 | TLV7（报车机蓝牙地址） | 建 socket 请求 |
 * |---|---|---|---|---|
 * | [USB] | 6 | 应答方 | 加密开启、还不知道对端蓝牙地址时发一次 | 只接受含 TCP 的请求，应答回 TCP 端口 |
 * | [BLUETOOTH] | 2 | 应答方 | 不发 | 还接受协议 0 的请求（开 RFCOMM 子通道），应答回 RFCOMM 通道号和 UUID |
 * | [WIFI] | 3 | 先当一次发起方，再当应答方 | 不发 | 同有线 |
 *
 * 蓝牙和 WiFi 通道上的设备是由蓝牙连接建立的，对端蓝牙地址已知，所以车机不报 TLV7。
 * WiFi 通道是车机在数据通道协商之后主动建立的，所以车机在这条通道上要多当一次握手发起方。
 *
 * 只有 [BLUETOOTH] 上处理数据通道协商（资源层命令 1、7）、消息层的探活（命令 1）和 WiFi 组网层的 MAC 交换；
 * WiFi 组网层的断开请求在 [BLUETOOTH] 和 [WIFI] 上都处理。[USB] 上这些条目照旧作为未处理事件交出。
 */
enum class NearbyLink(
    /** 握手、建 socket 请求里用的通道号。 */
    val channel: Int,
) {
    /** 有线：手机切成 USB 网卡后连进来的第一条 TCP。 */
    USB(6),

    /** 经典蓝牙 RFCOMM：手机扫码或回连时连进来的那条。 */
    BLUETOOTH(2),

    /** WiFi（热点或直连组）上手机连进来的第一条 TCP。 */
    WIFI(3),
}
